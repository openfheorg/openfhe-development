"""D0.1 — the conjugate-invariant canonical embedding (decode matrix U), the slot
rotation group (g=5), the slot-order permutation P, and the basis norms.

Math contract (plan §4), N a power of two = CI rank = #real slots, m = 4N:
    nodes      xi_j   = 2 cos(pi (4j+1) / (2N)),            0 <= j < N
    decode U:  U[j,0] = 1;  U[j,i] = 2 cos(pi (4j+1) i / (2N)),  1 <= i < N
    encode  = U^{-1}.

Orthogonality (proved in tests): columns of U are mutually orthogonal with
    <u_0,u_0> = N ,  <u_i,u_i> = 2N (i>=1)
so  U^T U = diag(N, 2N, ..., 2N)  and  U^{-1} = diag(1/N, 1/2N, ..., 1/2N) U^T.
The 2:1 ratio between u_i and u_0 is the basis asymmetry the whole pipeline must
track (CIBasisScale); its absolute Kim-Song normalization is pinned in the noise model.

Rotations: G = (Z/4N)*/{+-1} = Z/N, generated by g=5. rot_group[k] = 5^k mod 4N.
The node visited at cyclic position k is 2cos(pi*5^k/(2N)); folding 5^k mod 4N into
the representative 4t+1 gives the permutation P (cyclic position -> natural index t).
"""
import mpmath

from .precision import cos, pi


def ci_nodes(N):
    """xi_j = 2 cos(pi (4j+1)/(2N)), j=0..N-1 (natural / '4j+1' order)."""
    return [2 * cos(pi() * (4 * j + 1) / (2 * N)) for j in range(N)]


def dense_U(N):
    """The CI decode matrix U (slots = U @ coeffs), natural slot order. N x N, real."""
    U = mpmath.matrix(N, N)
    for j in range(N):       # slot index
        U[j, 0] = mpmath.mpf(1)
        for i in range(1, N):  # coefficient index
            U[j, i] = 2 * cos(pi() * (4 * j + 1) * i / (2 * N))
    return U


def column_norm_sq(N):
    """Analytic basis norms [N, 2N, 2N, ..., 2N]; verified numerically in tests."""
    return [mpmath.mpf(N)] + [mpmath.mpf(2 * N)] * (N - 1)


def dense_U_inv_closed(N):
    """Closed-form inverse U^{-1} = diag(1/N, 1/2N, ..., 1/2N) @ U^T."""
    U = dense_U(N)
    w = column_norm_sq(N)
    Uinv = mpmath.matrix(N, N)
    for i in range(N):       # row of U^{-1}  = column i of U, scaled
        s = 1 / w[i]
        for j in range(N):
            Uinv[i, j] = s * U[j, i]
    return Uinv


def rot_group(N):
    """rot_group[k] = 5^k mod 4N, k=0..N-1 (matches OpenFHE PrecomputedValues)."""
    m = 4 * N
    out = []
    five = 1
    for _ in range(N):
        out.append(five)
        five = (five * 5) % m
    return out


def slot_perm_g5(N):
    """Permutation P: cyclic position k (slot order under g=5) -> natural index t,
    where 5^k mod 4N == +-(4t+1).  Bijection on {0,..,N-1}."""
    m = 4 * N
    P = []
    for k in range(N):
        r = pow(5, k, m)
        if r % 4 == 3:          # this is the -(4t+1) coset representative
            r = (m - r) % m     # fold by negation -> r % 4 == 1
        assert r % 4 == 1
        P.append((r - 1) // 4)
    assert sorted(P) == list(range(N)), "P is not a bijection"
    return P


def bit_reverse_perm(N):
    """Q[i] = bit-reversal of i over log2(N) bits (OpenFHE BitReverse ordering)."""
    bits = N.bit_length() - 1
    return [int(format(i, "0{}b".format(bits))[::-1], 2) for i in range(N)]


def inverse_perm(P):
    inv = [0] * len(P)
    for i, p in enumerate(P):
        inv[p] = i
    return inv
